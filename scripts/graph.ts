// Writes KNOWLEDGE_GRAPH.json at the repo root: `npm run graph`.
import fs from 'node:fs';
import { buildGraph } from '../src/system/graph.ts';
const g = buildGraph();
const count = (k: string, l: { kind: string }[]) => l.filter(x => x.kind === k).length;
fs.writeFileSync(new URL('../KNOWLEDGE_GRAPH.json', import.meta.url), JSON.stringify({
  about: 'BorNiz one-system graph. Nodes: page (route), surface (screen/prototype), object (data, spec authority), role, event (service), doc. Generated by scripts/graph.ts from src/system/registry.ts + graph.ts; do not edit.',
  stats: Object.fromEntries(['page', 'surface', 'object', 'role', 'event', 'doc'].map(k => [k, count(k, g.nodes)])),
  ...g,
}, null, 1));
console.log('KNOWLEDGE_GRAPH.json', g.nodes.length, 'nodes', g.edges.length, 'edges');
